def example_train_template(name: str, equation: str) -> str:
    return f'''"""
train.py — {name}

Loads config.yaml, builds the data pipeline, model, problem and
trainer, then runs fit(). Generated by `aiplasma new example`;
edit the TODOs to match the real physics being modelled.
"""

import math
from pathlib import Path

import torch
import yaml

from core.base_trainer import TrainerConfig
from data.preprocessing.data_transformer import DataTransformer
from data_parser import DataSourceConfig, SyntheticDataSource
from data.sources.physical_tensor import CoordinateSystem, Domain, UnitSystem
from models.pinn.base_pinn import BasePINN
from solvers.pde_solver import AutogradPDESolver
from trainers.pinn_trainer import PINNTrainer

from problem import {name}Problem  # TODO: rename to match your generated problem class


def load_config() -> dict:
    with open(Path(__file__).parent / "config.yaml") as f:
        return yaml.safe_load(f)


def exact_solution(x, t, alpha=0.01):
    """TODO: replace with the real reference solution, or delete if none exists."""
    return torch.sin(math.pi * x) * torch.exp(torch.tensor(-alpha * math.pi ** 2) * t)


def main() -> None:
    cfg = load_config()

    data_cfg = DataSourceConfig(
        coord_system=CoordinateSystem.CARTESIAN,
        units=UnitSystem(spatial="m", temporal="s", field="normalized"),
        domain=Domain(x_range=(0.0, 1.0), t_range=(0.0, 1.0)),
    )
    source = SyntheticDataSource(
        solution_fn=exact_solution, config=data_cfg, n_points=cfg["data"]["n_points"]
    )
    batches = DataTransformer().transform([source.load()])
    n_val = max(1, int(len(batches) * cfg["data"]["val_ratio"]))
    train_batches, val_batches = batches[:-n_val] or batches, batches[-n_val:]

    model = BasePINN(
        input_dim=cfg["model"]["input_dim"],
        output_dim=cfg["model"]["output_dim"],
        hidden_layers=cfg["model"]["hidden_layers"],
        hidden_size=cfg["model"]["hidden_size"],
    )
    problem = {name}Problem(**cfg["physics_params"])
    solver = AutogradPDESolver(equation=problem.equation)
    trainer = PINNTrainer(
        model=model,
        problem=problem,
        solver=solver,
        config=TrainerConfig(
            max_epochs=cfg["training"]["max_epochs"],
            val_frequency=cfg["training"]["val_frequency"],
            log_frequency=cfg["training"]["log_frequency"],
        ),
    )

    history = trainer.fit(train_batches=train_batches, val_batches=val_batches)

    Path("checkpoints").mkdir(exist_ok=True)
    model.save("checkpoints/model.pt")
    print(f"Trained for {{len(history.epochs)}} epochs. Final checkpoint: checkpoints/model.pt")


if __name__ == "__main__":
    main()
'''


